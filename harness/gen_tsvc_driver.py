#!/usr/bin/env python3
"""gen_tsvc_driver.py MAINS_F [kernel ...] > tsvc_driver.c

Emit a C main() that calls the TSVC Fortran kernels exactly as mains.f's main
loop does (same order, same extra arguments, set-up copied from mains.f's
`set`), with ld=1000, n=100, ntimes=100.  Naming kernels (e.g. s111 vpvtv)
limits the driver to those, for a short pipetrace window.
"""
import re
import sys

src = open(sys.argv[1]).read().splitlines()
only = set(k.lower() for k in sys.argv[2:])

# join Fortran continuation lines (non-blank in column 6)
lines = []
for l in src:
    if l[:1] in ('c', 'C', '*'):
        continue
    if len(l) > 5 and l[5] not in (' ', '0') and lines:
        lines[-1] += l[6:].strip()
    else:
        lines.append(l)

calls = []
in_loop = False
for l in lines:
    s = l.strip().lower().replace(' ', '')
    if s.startswith('do1000'):
        in_loop = True
        continue
    if s.startswith('1000continue'):
        break
    m = re.match(r'call([sv][0-9a-z]+)\((ntimes,.*)\)$', s)
    if in_loop and m:
        calls.append((m.group(1), m.group(2).split(',')))

argmap = {
    'ntimes': '&ntimes', 'ld': '&ld', 'n': '&n', 'ctime': '&ctime', 'dtime': '&dtime',
    'a': 'a', 'b': 'b', 'c': 'c', 'd': 'd', 'e': 'e', 'aa': 'aa', 'bb': 'bb', 'cc': 'cc',
    'n1': '&n1', 'n3': '&n3', 's1': '&s1', 's2': '&s2', 'ip': 'ip', 'indx': 'indx',
    'c471s': '&c471s', 'n/2': '&nhalf',
}

out = []
out.append('/* generated by gen_tsvc_driver.py from mains.f -- do not edit */')
out.append('#include "swp_rt.h"')
out.append('#define LD 1000')
out.append('static float a[LD], b[LD], c[LD], d[LD], e[LD];')
out.append('static float aa[LD * LD], bb[LD * LD], cc[LD * LD];')
out.append('static int ip[LD], indx[LD];')
names = sorted(set(k for k, _ in calls if not only or k in only))
for k in names:
    out.append('extern void %s_();' % k)
out.append('int main(void) {')
out.append('  int ld = LD, n = 100, ntimes = 100, nhalf = 50, n1 = 1, n3 = 1;')
out.append('  float ctime = 0.0f, dtime = 0.0f, c471s = 0.0f, s1 = 1.0f, s2 = 2.0f;')
out.append('  for(int i = 0; i < LD; i += 5) {')
out.append('    ip[i] = i + 5;')
out.append('    ip[i + 1] = i + 3;')
out.append('    ip[i + 2] = i + 1;')
out.append('    ip[i + 3] = i + 4;')
out.append('    ip[i + 4] = i + 2;')
out.append('  }')
out.append('  for(int i = 0; i < LD; i++) {')
out.append('    indx[i] = ((i + 1) % 4) + 1;')
out.append('  }')
out.append('  swp_puts("TSVC_BEGIN\\n");')
for k, args in calls:
    if only and k not in only:
        continue
    out.append('  %s_(%s);' % (k, ', '.join(argmap[x] for x in args)))
out.append('  swp_puts("TSVC_DONE\\n");')
out.append('  return 0;')
out.append('}')
print('\n'.join(out))
